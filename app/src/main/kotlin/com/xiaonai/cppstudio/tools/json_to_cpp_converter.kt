package com.xiaonai.cppstudio.tools

/**
 * JSON → C++17 结构体转换器（宿主内置工具引擎，纯 Kotlin，离线可用）。
 *
 * 输出规则（粘进 .h/.hpp 即可编译，不引入第三方依赖）：
 * - 每个 JSON 对象 → `struct Name { ... };`，字段严格保持 JSON 顺序
 * - string → std::string；bool → bool；带小数点/指数的数字 → double
 * - 整数按观测值取宽度：装得进 32 位 → std::int32_t，否则 std::int64_t
 * - 某字段出现过 null → std::optional<T>；数组里的 null 元素直接忽略
 * - 数组 → std::vector<T>：T 由全部非 null 元素合并推断，类型冲突退化为 std::string（附注释）
 * - 嵌套对象 → 在父结构体之前声明独立 struct，名字由字段名 PascalCase 推导（数组元素取单数）
 * - 空对象 → std::map<std::string, std::string>；空数组/元素类型未知 → std::vector<std::string>
 * - 字段名：合法 C++ 标识符原样保留；否则转 snake_case，并用 `// JSON key "..."` 注释保住原 key；
 *   关键字加尾下划线（class → class_）；同结构体内重名追加 _2/_3
 * - 顶部只输出真正用到的 #include（<cstdint> <map> <optional> <string> <vector>），
 *   并带 `// generated by CppStudio` 标注
 * - 根节点是数组时输出 `using Name = std::vector<T>;`（元素为对象时先声明 NameItem 结构体）
 * - 末尾附一段整段注释掉的 nlohmann/json from_json 草稿（根节点是对象时），保持产出零依赖
 *
 * 解析器在标准 JSON 之上做了一点容错：允许尾逗号、单引号字符串、裸键名，
 * 方便从日志/JS 代码里直接粘贴。
 */
object json_to_cpp_converter {

    /** 入口：JSON 文本 → C++17 结构体定义。根节点必须是对象或数组。 */
    fun convert(json_text: String, struct_name: String = "AutoGenerated"): Result<String> = runCatching {
        if (json_text.isBlank()) throw IllegalArgumentException("请输入 JSON 内容")
        val root = infer(json_parser(json_text).parse())
        cpp_emitter().render(root, sanitize_struct_name(struct_name))
    }

    // ---------- 推断 ----------

    private fun infer(node: json_node): cpp_type = when (node) {
        is json_string_node -> cpp_string
        is json_bool_node -> cpp_bool
        is json_null_node -> cpp_null
        is json_number_node -> infer_number(node.raw)
        is json_array_node -> cpp_vector(unify_all(node.items))
        is json_object_node -> cpp_object(
            node.entries.map { (key, value) -> cpp_member(key, infer(value)) }
        )
    }

    /** 数字看原始字面量：带小数点/指数 → double；整数按 32 位范围选 int32/int64；超出 Long 退化 double */
    private fun infer_number(raw: String): cpp_type {
        if (raw.contains('.') || raw.contains('e') || raw.contains('E')) return cpp_double
        return raw.toLongOrNull()
            ?.let {
                if (it >= Int.MIN_VALUE.toLong() && it <= Int.MAX_VALUE.toLong()) cpp_int32 else cpp_int64
            }
            ?: cpp_double
    }

    /**
     * 数组元素类型合并：null 元素不参与推断（[null,"a"] → vector<std::string>），
     * 空数组或全 null → cpp_unknown（渲染为 std::string 并加注释）。
     */
    private fun unify_all(items: List<json_node>): cpp_type {
        var result: cpp_type? = null
        for (item in items) {
            if (item is json_null_node) continue
            val inferred = infer(item)
            result = result?.let { unify(it, inferred) } ?: inferred
        }
        return result ?: cpp_unknown
    }

    private fun unify(a: cpp_type, b: cpp_type): cpp_type = when {
        a == b -> a
        a is cpp_optional -> cpp_optional(unify(a.inner, b))
        b is cpp_optional -> cpp_optional(unify(a, b.inner))
        a == cpp_null -> cpp_optional(b)
        b == cpp_null -> cpp_optional(a)
        a == cpp_unknown || b == cpp_unknown -> cpp_unknown
        a is cpp_object && b is cpp_object -> merge_objects(a, b)
        a is cpp_vector && b is cpp_vector -> cpp_vector(unify(a.elem, b.elem))
        is_number(a) && is_number(b) -> number_wider(a, b)
        else -> cpp_unknown
    }

    private fun is_number(type: cpp_type): Boolean =
        type == cpp_int32 || type == cpp_int64 || type == cpp_double

    private fun number_wider(a: cpp_type, b: cpp_type): cpp_type = when {
        a == cpp_double || b == cpp_double -> cpp_double
        a == cpp_int64 || b == cpp_int64 -> cpp_int64
        else -> cpp_int32
    }

    /** 跨数组元素合并对象：按原始 key 对齐，同 key 类型再合并；保持首次出现顺序 */
    private fun merge_objects(a: cpp_object, b: cpp_object): cpp_object {
        val merged = LinkedHashMap<String, cpp_member>()
        a.members.forEach { merged[it.key] = it }
        for (member in b.members) {
            val existing = merged[member.key]
            merged[member.key] = if (existing == null) {
                member
            } else {
                cpp_member(member.key, unify(existing.type, member.type))
            }
        }
        return cpp_object(merged.values.toList())
    }
}

// ---------- 类型树 ----------

private sealed class cpp_type

/** 值是 null（合并时变成 optional，渲染为 std::optional<std::string>） */
private object cpp_null : cpp_type()

/** 类型冲突/未知（渲染为 std::string，并加注释说明） */
private object cpp_unknown : cpp_type()
private object cpp_string : cpp_type()
private object cpp_bool : cpp_type()
private object cpp_double : cpp_type()
private object cpp_int32 : cpp_type()
private object cpp_int64 : cpp_type()
private data class cpp_optional(val inner: cpp_type) : cpp_type()
private data class cpp_vector(val elem: cpp_type) : cpp_type()
private data class cpp_object(val members: List<cpp_member>) : cpp_type()
private data class cpp_member(val key: String, val type: cpp_type)

// ---------- 渲染 ----------

/** 一个待输出的字段：name 已定稿，type 是 C++ 类型表达式，note 是行尾注释 */
private class cpp_field_def(val key: String, val name: String, val type: String, val note: String?)

/** 一个待输出的 struct：出现在列表里时，它的依赖一定已经在更前面 */
private class cpp_struct_def(val name: String, val fields: List<cpp_field_def>)

/** 字段名分配结果：最终名字 + 需要附带的注释（原 key / 关键字 / 重名） */
private class cpp_field_assignment(val name: String, val note: String?)

/** 头文件按固定（字母序）顺序输出，保证同样输入产出稳定文本 */
private val cpp_include_order = listOf("cstdint", "map", "optional", "string", "vector")

/**
 * 一次转换的渲染状态：收集 struct 定义（子结构体一定排在父结构体前面）、
 * 已占用的类型名、以及真正用到的标准库头文件。
 */
private class cpp_emitter {

    private val structs = mutableListOf<cpp_struct_def>()
    private val used_names = mutableSetOf<String>()
    private val includes = sortedSetOf<String>()

    fun render(root: cpp_type, root_name: String): String {
        used_names += root_name
        val root_lines = mutableListOf<String>()
        when (root) {
            is cpp_object -> if (root.members.isEmpty()) {
                // 空对象：没有字段可推断，退化成字符串字典
                includes += "map"
                includes += "string"
                root_lines += "using $root_name = std::map<std::string, std::string>;"
            } else {
                declare_object(root, root_name)
            }
            is cpp_vector -> {
                val elem_type = if (root.elem is cpp_object && root.elem.members.isNotEmpty()) {
                    declare_object(root.elem, unique_name("${root_name}Item"))
                } else {
                    type_expr(root.elem, "${root_name}Item", in_array = true)
                }
                includes += "vector"
                root_lines += "using $root_name = std::vector<$elem_type>;"
            }
            else -> throw IllegalArgumentException("根节点必须是 JSON 对象或数组")
        }

        val sb = StringBuilder()
        sb.append("// generated by CppStudio - JSON to C++ structs (C++17)\n")
        for (header in cpp_include_order) {
            if (header in includes) sb.append("#include <").append(header).append(">\n")
        }
        for (struct in structs) {
            sb.append('\n').append(render_struct(struct)).append('\n')
        }
        if (root_lines.isNotEmpty()) {
            sb.append('\n')
            for (line in root_lines) sb.append(line).append('\n')
        }
        if (root is cpp_object && structs.isNotEmpty()) {
            sb.append('\n').append(render_adapter(structs)).append('\n')
        }
        return sb.toString().trimEnd('\n')
    }

    /** 声明一个结构体（先递归声明它的嵌套结构体，再把自己追加到列表末尾） */
    private fun declare_object(obj: cpp_object, name: String): String {
        // 先把所有字段的 C++ 类型算出来：这一步会登记嵌套结构体，占用的类型名要在起字段名时避开
        val type_texts = obj.members.map { type_expr(it.type, it.key, in_array = false) }
        val reserved = used_names + name
        val used_field_names = mutableSetOf<String>()
        val fields = obj.members.mapIndexed { index, member ->
            val assignment = assign_field_name(member.key, used_field_names, reserved)
            cpp_field_def(
                key = member.key,
                name = assignment.name,
                type = type_texts[index],
                note = combine_notes(assignment.note, type_note(member.type))
            )
        }
        structs += cpp_struct_def(name, fields)
        return name
    }

    /** 类型树 → C++ 类型表达式；key 是引入这个类型的 JSON 字段名（用来给新结构体命名） */
    private fun type_expr(type: cpp_type, key: String, in_array: Boolean): String = when (type) {
        cpp_null -> {
            includes += "optional"
            includes += "string"
            "std::optional<std::string>"
        }
        cpp_unknown, cpp_string -> {
            includes += "string"
            "std::string"
        }
        cpp_bool -> "bool"
        cpp_double -> "double"
        cpp_int32 -> {
            includes += "cstdint"
            "std::int32_t"
        }
        cpp_int64 -> {
            includes += "cstdint"
            "std::int64_t"
        }
        is cpp_optional -> {
            includes += "optional"
            "std::optional<" + type_expr(type.inner, key, in_array) + ">"
        }
        is cpp_vector -> {
            includes += "vector"
            "std::vector<" + type_expr(type.elem, key, in_array = true) + ">"
        }
        is cpp_object -> if (type.members.isEmpty()) {
            includes += "map"
            includes += "string"
            "std::map<std::string, std::string>"
        } else {
            declare_object(type, unique_name(object_struct_name(key, in_array)))
        }
    }

    private fun render_struct(struct: cpp_struct_def): String {
        val sb = StringBuilder()
        sb.append("struct ").append(struct.name).append(" {\n")
        for (field in struct.fields) {
            sb.append("    ").append(field.type).append(' ').append(field.name).append(';')
            field.note?.let { sb.append("  // ").append(it) }
            sb.append('\n')
        }
        sb.append("};")
        return sb.toString()
    }

    /** 末尾的 nlohmann/json 适配器草稿：整段注释，保证输出零依赖 */
    private fun render_adapter(structs: List<cpp_struct_def>): String {
        val lines = mutableListOf(
            "// Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).",
            "// Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys."
        )
        for (struct in structs) {
            lines += "//"
            lines += "// inline void from_json(const nlohmann::json& j, ${struct.name}& v) {"
            for (field in struct.fields) {
                lines += "//     j.at(\"${escape_comment(field.key)}\").get_to(v.${field.name});"
            }
            lines += "// }"
        }
        return lines.joinToString("\n")
    }

    /** 占住一个类型名；重名时追加 2/3/... 序号 */
    private fun unique_name(base: String): String {
        var name = base
        var index = 2
        while (!used_names.add(name)) {
            name = "$base$index"
            index++
        }
        return name
    }
}

// ---------- 命名辅助 ----------

/** 由 JSON 字段名推导结构体名：PascalCase；数组元素取单数（items → Item） */
private fun object_struct_name(key: String, in_array: Boolean): String {
    val pascal = pascal_name(key).ifEmpty { "Item" }
    if (!in_array) return pascal
    val plural = key.length > 1 && key.endsWith("s") && !key.endsWith("ss")
    if (!plural) return pascal
    return pascal.dropLast(1).ifEmpty { pascal }
}

/** 用户输入的结构体名 → 合法 PascalCase 标识符 */
private fun sanitize_struct_name(input: String): String {
    val cleaned = pascal_name(input)
    return cleaned.ifEmpty { "AutoGenerated" }
}

/** 任意文本 → PascalCase（非 ASCII 字母数字都当分隔符；数字开头补 Struct 前缀） */
private fun pascal_name(input: String): String {
    val words = mutableListOf<String>()
    val current = StringBuilder()
    for (c in input.trim()) {
        if (c.is_ascii_alnum()) {
            current.append(c)
        } else if (current.isNotEmpty()) {
            words += current.toString()
            current.clear()
        }
    }
    if (current.isNotEmpty()) words += current.toString()
    if (words.isEmpty()) return ""
    val joined = words.joinToString("") { word ->
        val first = word[0]
        if (first in 'a'..'z') first.uppercaseChar() + word.substring(1) else word
    }
    return if (joined[0].is_ascii_digit()) "Struct$joined" else joined
}

/** 任意 key → snake_case 字段名（非 ASCII 字母数字压成下划线；数字开头补 field_ 前缀） */
private fun sanitize_field_name(key: String): String {
    val sb = StringBuilder()
    var pending_separator = false
    for (c in key) {
        if (c.is_ascii_alnum()) {
            sb.append(c.lowercaseChar())
            pending_separator = false
        } else if (!pending_separator && sb.isNotEmpty()) {
            sb.append('_')
            pending_separator = true
        }
    }
    var name = sb.toString().trimEnd('_')
    if (name.isEmpty()) name = "field"
    if (name[0].is_ascii_digit()) name = "field_$name"
    if (name in cpp_reserved_names) name = "${name}_"
    return name
}

/**
 * 分配字段名：合法标识符原样保留；关键字加尾下划线；其余转 snake_case。
 * 同一结构体内重名追加 _2/_3，并且避开结构体自身/嵌套结构体已经占用的名字
 * （C++ 里成员名会遮蔽同作用域的类型名，`User User;` 会被当成构造函数）。
 */
private fun assign_field_name(
    key: String,
    used: MutableSet<String>,
    reserved: Set<String>
): cpp_field_assignment {
    val notes = mutableListOf<String>()
    val base = when {
        is_cpp_identifier(key) && key !in cpp_reserved_names -> key
        is_cpp_identifier(key) -> {
            notes += "JSON key \"${escape_comment(key)}\" (reserved word)"
            "${key}_"
        }
        else -> {
            notes += "JSON key \"${escape_comment(key)}\""
            sanitize_field_name(key)
        }
    }
    var name = base
    var index = 2
    while (!used.add(name) || name in reserved) {
        name = "${base}_$index"
        index++
    }
    if (index > 2) notes += "duplicate field name"
    return cpp_field_assignment(name, combine_notes(*notes.toTypedArray()))
}

/** 类型层面的说明注释：退化/空容器时给用户一个交代 */
private fun type_note(type: cpp_type): String? = when (type) {
    cpp_null -> "always null in the sample"
    cpp_unknown -> "mixed JSON types, fell back to std::string"
    is cpp_optional -> type_note(type.inner)
    is cpp_vector -> when (val elem = type.elem) {
        cpp_unknown -> "untyped array elements, fell back to std::string"
        is cpp_object -> if (elem.members.isEmpty()) "array of empty JSON objects" else null
        else -> type_note(elem)
    }
    is cpp_object -> if (type.members.isEmpty()) "empty JSON object" else null
    else -> null
}

private fun combine_notes(vararg notes: String?): String? {
    val parts = notes.filterNotNull().filter { it.isNotBlank() }
    return if (parts.isEmpty()) null else parts.joinToString("; ")
}

/** 注释里保留原始 key：只转义会破坏单行注释/字符串的字符 */
private fun escape_comment(text: String): String {
    val sb = StringBuilder()
    for (c in text) {
        when {
            c == '\\' -> sb.append("\\\\")
            c == '"' -> sb.append("\\\"")
            c == '\n' -> sb.append("\\n")
            c == '\r' -> sb.append("\\r")
            c == '\t' -> sb.append("\\t")
            c < ' ' -> sb.append('?')
            else -> sb.append(c)
        }
    }
    return sb.toString()
}

private fun is_cpp_identifier(text: String): Boolean {
    if (text.isEmpty()) return false
    val first = text[0]
    if (first != '_' && !first.is_ascii_letter()) return false
    return text.all { it == '_' || it.is_ascii_alnum() }
}

private fun Char.is_ascii_letter(): Boolean = this in 'a'..'z' || this in 'A'..'Z'
private fun Char.is_ascii_digit(): Boolean = this in '0'..'9'
private fun Char.is_ascii_alnum(): Boolean = is_ascii_letter() || is_ascii_digit()

/** C++17 关键字/替代记号：命中后字段名要加尾下划线 */
private val cpp_keywords: Set<String> = setOf(
