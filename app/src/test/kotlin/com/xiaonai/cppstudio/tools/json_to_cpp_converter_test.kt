package com.xiaonai.cppstudio.tools

import com.google.common.truth.Truth.assertThat
import org.junit.Test

/**
 * JSON → C++17 结构体转换器回归：
 * 输出的代码用户会直接粘进 .h/.hpp，类型推断/命名/头文件/声明顺序任何回退都是坏体验，
 * 这里锁住各关键路径的精确输出（样例均用 g++ -std=c++17 -fsyntax-only 校验过）。
 */
class json_to_cpp_converter_test {

    private fun convert(json: String, struct_name: String = "AutoGenerated"): String =
        json_to_cpp_converter.convert(json, struct_name).getOrThrow()

    @Test
    fun `basic scalars map to std types`() {
        val out = convert(
            """{"name": "CppStudio", "stars": 128, "score": 4.9, "active": true, "note": null, "user_name": "yitong"}"""
        )
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <cstdint>
            #include <optional>
            #include <string>

            struct AutoGenerated {
                std::string name;
                std::int32_t stars;
                double score;
                bool active;
                std::optional<std::string> note;  // always null in the sample
                std::string user_name;
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("name").get_to(v.name);
            //     j.at("stars").get_to(v.stars);
            //     j.at("score").get_to(v.score);
            //     j.at("active").get_to(v.active);
            //     j.at("note").get_to(v.note);
            //     j.at("user_name").get_to(v.user_name);
            // }
            """.trimIndent()
        )
    }

    @Test
    fun `nested object is declared before its parent`() {
        val out = convert("""{"id": 1, "author": {"name": "y", "vip": true}}""")
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <cstdint>
            #include <string>

            struct Author {
                std::string name;
                bool vip;
            };

            struct AutoGenerated {
                std::int32_t id;
                Author author;
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, Author& v) {
            //     j.at("name").get_to(v.name);
            //     j.at("vip").get_to(v.vip);
            // }
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("id").get_to(v.id);
            //     j.at("author").get_to(v.author);
            // }
            """.trimIndent()
        )
    }

    @Test
    fun `array of objects merges fields and names the element struct singular`() {
        val out = convert("""{"items": [{"a": 1, "b": "x"}, {"a": 2.5, "c": true}]}""")
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <string>
            #include <vector>

            struct Item {
                double a;
                std::string b;
                bool c;
            };

            struct AutoGenerated {
                std::vector<Item> items;
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, Item& v) {
            //     j.at("a").get_to(v.a);
            //     j.at("b").get_to(v.b);
            //     j.at("c").get_to(v.c);
            // }
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("items").get_to(v.items);
            // }
            """.trimIndent()
        )
    }

    @Test
    fun `field names keep valid keys, sanitize the rest and dedupe`() {
        val out = convert(
            """{"user name": 1, "user_name": 2, "2fa": true, "class": "x", "id": [1, "a"]}"""
        )
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <cstdint>
            #include <string>
            #include <vector>

            struct AutoGenerated {
                std::int32_t user_name;  // JSON key "user name"
                std::int32_t user_name_2;  // duplicate field name
                bool field_2fa;  // JSON key "2fa"
                std::string class_;  // JSON key "class" (reserved word)
                std::vector<std::string> id;  // untyped array elements, fell back to std::string
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("user name").get_to(v.user_name);
            //     j.at("user_name").get_to(v.user_name_2);
            //     j.at("2fa").get_to(v.field_2fa);
            //     j.at("class").get_to(v.class_);
            //     j.at("id").get_to(v.id);
            // }
            """.trimIndent()
        )
    }

    @Test
    fun `root array becomes a vector alias over the element struct`() {
        val out = convert("""[{"x": 1}]""")
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <cstdint>
            #include <vector>

            struct AutoGeneratedItem {
                std::int32_t x;
            };

            using AutoGenerated = std::vector<AutoGeneratedItem>;
            """.trimIndent()
        )
    }

    @Test
    fun `number literals keep precision semantics`() {
        // 1.0 必须是 double（不能被当成整型）；超 32 位是 int64；空数组退化为 vector<string>
        val out = convert("""{"n": 1.0, "big": 9999999999, "list": []}""")
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <cstdint>
            #include <string>
            #include <vector>

            struct AutoGenerated {
                double n;
                std::int64_t big;
                std::vector<std::string> list;  // untyped array elements, fell back to std::string
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("n").get_to(v.n);
            //     j.at("big").get_to(v.big);
            //     j.at("list").get_to(v.list);
            // }
            """.trimIndent()
        )
    }

    @Test
    fun `lenient parsing accepts trailing comma, single quotes and bare keys`() {
        val out = convert("{'a': 1,}")
        assertThat(out).contains("std::int32_t a;")
        assertThat(out).startsWith("// generated by CppStudio")
        assertThat(convert("""{a: 1}""")).contains("std::int32_t a;")
    }

    @Test
    fun `parse error reports line number`() {
        val result = json_to_cpp_converter.convert("""{"a": }
{"b": 1}""", "Foo")
        assertThat(result.isFailure).isTrue()
        assertThat(result.exceptionOrNull()!!.message).contains("第 1 行")
    }

    @Test
    fun `scalar root is rejected`() {
        assertThat(json_to_cpp_converter.convert("\"hello\"").isFailure).isTrue()
        assertThat(json_to_cpp_converter.convert("null").isFailure).isTrue()
    }

    @Test
    fun `custom struct name is sanitized to pascal case`() {
        val custom = convert("""{"a":1}""", "my config-v2")
        assertThat(custom).startsWith("// generated by CppStudio")
        assertThat(custom).contains("struct MyConfigV2 {")
        assertThat(convert("""{"a":1}""", "2fast")).contains("struct Struct2fast {")
        assertThat(convert("""{"a":1}""", "   ")).contains("struct AutoGenerated {")
    }

    @Test
    fun `nulls become optional and mixed arrays fall back to string`() {
        val out = convert("""{"maybe": [null, "a"], "weird": [[1, "x"], [2]]}""")
        assertThat(out).isEqualTo(
            """
            // generated by CppStudio - JSON to C++ structs (C++17)
            #include <string>
            #include <vector>

            struct AutoGenerated {
                std::vector<std::string> maybe;
                std::vector<std::vector<std::string>> weird;  // untyped array elements, fell back to std::string
            };

            // Optional nlohmann/json adapter sketch (commented out, needs <nlohmann/json.hpp>).
            // Uncomment if you parse this type with nlohmann/json; fields keep their original JSON keys.
            //
            // inline void from_json(const nlohmann::json& j, AutoGenerated& v) {
            //     j.at("maybe").get_to(v.maybe);
            //     j.at("weird").get_to(v.weird);
            // }
            """.trimIndent()
        )
    }
}
